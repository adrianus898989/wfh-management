-- Near-real-time synchronization for the two private August 2026 attendance
-- sheets. The Google reader pushes a complete A:N snapshot to an Edge
-- Function; this migration provides an allowlisted, atomic ingest boundary.
-- March-July sources cannot be selected by this function and remain immutable.

create table if not exists public.attendance_sheet_sync_runs (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null unique,
  source_id uuid not null references public.attendance_sheet_sources(id) on delete restrict,
  trigger_kind text not null,
  status text not null default 'running',
  snapshot_hash text not null,
  previous_snapshot_hash text,
  read_row_count integer not null default 0,
  raw_record_count integer not null default 0,
  canonical_record_count integer not null default 0,
  mirror_record_count integer not null default 0,
  inserted_count integer not null default 0,
  updated_count integer not null default 0,
  deleted_count integer not null default 0,
  unchanged_count integer not null default 0,
  matched_count integer not null default 0,
  unmatched_count integer not null default 0,
  ambiguous_count integer not null default 0,
  error_message text,
  details jsonb not null default '{}'::jsonb,
  result jsonb,
  captured_at timestamptz,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  constraint attendance_sheet_sync_runs_trigger_check
    check (trigger_kind in ('change', 'daily_reconcile', 'manual')),
  constraint attendance_sheet_sync_runs_status_check
    check (status in ('running', 'success', 'unchanged', 'failed')),
  constraint attendance_sheet_sync_runs_hash_check
    check (snapshot_hash ~ '^[0-9a-f]{64}$'),
  constraint attendance_sheet_sync_runs_previous_hash_check
    check (
      previous_snapshot_hash is null
      or previous_snapshot_hash ~ '^[0-9a-f]{64}$'
    ),
  constraint attendance_sheet_sync_runs_counts_check
    check (
      read_row_count >= 0
      and raw_record_count >= 0
      and canonical_record_count >= 0
      and mirror_record_count >= 0
      and inserted_count >= 0
      and updated_count >= 0
      and deleted_count >= 0
      and unchanged_count >= 0
      and matched_count >= 0
      and unmatched_count >= 0
      and ambiguous_count >= 0
    ),
  constraint attendance_sheet_sync_runs_details_object_check
    check (jsonb_typeof(details) = 'object')
);

create table if not exists public.attendance_sheet_sync_changes (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.attendance_sheet_sync_runs(id) on delete restrict,
  source_id uuid not null references public.attendance_sheet_sources(id) on delete restrict,
  operation text not null,
  source_block text not null,
  source_row integer not null,
  source_item_key text not null,
  record_id uuid,
  before_record jsonb,
  after_record jsonb,
  created_at timestamptz not null default now(),
  constraint attendance_sheet_sync_changes_operation_check
    check (operation in ('insert', 'update', 'delete')),
  constraint attendance_sheet_sync_changes_source_row_check
    check (source_row > 0),
  constraint attendance_sheet_sync_changes_before_object_check
    check (before_record is null or jsonb_typeof(before_record) = 'object'),
  constraint attendance_sheet_sync_changes_after_object_check
    check (after_record is null or jsonb_typeof(after_record) = 'object')
);

-- Persistent private staging avoids trusting caller-owned temporary objects in
-- a SECURITY DEFINER function. Rows exist only for the ingest transaction.
create table if not exists attendance_private.attendance_sheet_sync_stage (
  run_id uuid not null references public.attendance_sheet_sync_runs(id) on delete cascade,
  source_id uuid not null references public.attendance_sheet_sources(id) on delete restrict,
  source_block text not null,
  source_row integer not null,
  source_item_key text not null default 'primary',
  kind text not null,
  event_date date,
  event_kind text not null,
  reason text,
  note text,
  amount numeric,
  raw_amount text,
  employee_no_raw text,
  employee_name_raw text,
  employee_status_raw text,
  team_name_raw text,
  position_name_raw text,
  country_raw text,
  platform_raw text,
  manager_raw text,
  raw_values jsonb not null default '{}'::jsonb,
  content_hash text not null,
  is_mirror boolean not null default false,
  source_updated_at timestamptz,
  primary key (run_id, source_block, source_row, source_item_key),
  constraint attendance_sheet_sync_stage_source_row_check check (source_row > 0),
  constraint attendance_sheet_sync_stage_kind_check
    check (kind in ('attendance', 'resignation', 'adjustment')),
  constraint attendance_sheet_sync_stage_hash_check
    check (content_hash ~ '^[0-9a-f]{64}$'),
  constraint attendance_sheet_sync_stage_raw_values_check
    check (jsonb_typeof(raw_values) = 'object')
);

