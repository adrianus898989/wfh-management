import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import test from 'node:test'

const page = await readFile(new URL('../pages/AdminUsersPage.jsx', import.meta.url), 'utf8')
const endpoint = await readFile(new URL('../../supabase/functions/admin-accounts/index.ts', import.meta.url), 'utf8')
const recoveryEndpoint = await readFile(new URL('../../supabase/functions/admin-accounts/recovery.ts', import.meta.url), 'utf8')
