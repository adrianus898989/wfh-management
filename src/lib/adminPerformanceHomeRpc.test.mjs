test('connectivity request consistency ignores late responses and labels retained snapshots',()=>{
  assert.equal(isCurrentLiveRequest(true,7,7),true)
  assert.equal(isCurrentLiveRequest(true,8,7),false)
  assert.equal(isCurrentLiveRequest(false,7,7),false)
  assert.equal(isSnapshotForRequest({hasData:true,scopeKey:'scope-a',key:'records:today',label:'今天考试记录'},'scope-a','records:today'),true)
  assert.equal(isSnapshotForRequest({hasData:true,scopeKey:'scope-a',key:'grading:all',label:'全部待批改'},'scope-a','records:today'),false)
  assert.equal(isSnapshotForRequest({hasData:true,scopeKey:'scope-b',key:'records:today',label:'今天考试记录'},'scope-a','records:today'),false)
  assert.match(staleSnapshotNotice('日期 2026-08-01 至 2026-08-28'),/当前保留最近一次成功结果/)
  assert.match(staleSnapshotNotice('日期 2026-08-01 至 2026-08-28'),/2026-08-01/)
})

